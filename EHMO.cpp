double EHMO::YlmbyName(int idx, vector3 pos)
{
    SlateBasisSets * bas= getBasisSet(idx);
    vector3 v=bas->coord-pos;
    QString AOName=bas->orbitalName;

    double r=v.length();
    if(r<0.0001) r=0.0001;

    //uint l=bas->l;
    //int m=bas->m;

    double x=v.x(),y=v.y(),z=v.z();

    double ylm=1.0;
    double pi4=4.0*pi;
    double r2=r*r,r3=r2*r;

    if(AOName=="S")
        ylm=sqrt(1/pi4);

    if(AOName.startsWith("P")) {
        if  (AOName.startsWith("Px"))       ylm=sqrt(3/pi4)*x/r;
        if  (AOName.startsWith("Py"))       ylm=sqrt(3/pi4)*y/r;
        if  (AOName.startsWith("Pz"))       ylm=sqrt(3/pi4)*z/r;
    }



    if(AOName.startsWith("D")) {
        if  (AOName.startsWith("Dxy"))         ylm=0.5*sqrt(15/pi)*x*y/r2;                 //-2
        if  (AOName.startsWith("Dyz"))         ylm=0.5*sqrt(15/pi)*y*z/r2;                 //-1
        if  (AOName.startsWith("Dz2"))         ylm=0.25*sqrt(5.0/pi)*(2*z*z-x*x-y*y)/r2;   //0
        if  (AOName.startsWith("Dxz"))         ylm=0.5*sqrt(15.0/pi)*x*z/r2;               //1
        if  (AOName.startsWith("Dx2-y2"))      ylm=0.25*sqrt(15.0/pi)*(x*x-y*y)/r2;        //2
    }



    if(AOName.startsWith("F")) {
        if  (AOName.startsWith("Fy(3x2-y2)"))   //-3
            ylm=0.25*sqrt(35.0/2.0/pi)*(3.0*x*x-y*y)*y/r3;

        if  (AOName.startsWith("Fx(x2-3y2)"))     //3
            ylm=0.25*sqrt(35.0/2.0/pi)*(x*x-3.0*y*y)*x/r3 ;

        if  (AOName.startsWith("Fxyz"))        //-2
            ylm=0.5*sqrt(105.0/pi)*x*y*z/r3;

        if  (AOName.startsWith("Fz(x2-y2)"))   //2
            ylm=0.25*sqrt(105.0/pi)*(x*x-y*y)*z/r3 ;

        if  (AOName.startsWith("Fyz2"))        //-1
            ylm=0.25*sqrt(21.0/2.0/pi)*y*(4.0*z*z-x*x-y*y)/r3;

        if  (AOName.startsWith("Fxz2"))        //1
            ylm=0.25*sqrt(21.0/2.0/pi)*x*(4.0*z*z-x*x-y*y)/r3;

        if  (AOName.startsWith("Fz3"))          //0
            ylm=0.25*sqrt(7.0/pi)*(2.0*z*z-3.0*x*x-3.0*y*y)/r3;
    }

    return ylm;
}


double EHMO::Ylm(int idx,vector3 pos)
{
    SlateBasisSets * bas= getBasisSet(idx);

    vector3 v=bas->coord-pos;

    double r=v.length();
    if(r<0.0001) r=0.0001;

    uint l=bas->l;
    int m=bas->m;

    double x=v.x(),y=v.y(),z=v.z();

    double ylm=1.0;
    double pi4=4.0*pi;
    double r2=r*r,r3=r2*r;

    switch (l)
    {
    case 0:
        ylm=sqrt(1/pi4);
        break;

    case 1:
        if(m==-1)       ylm=sqrt(3/pi4)*x/r;
        if(m==1)        ylm=sqrt(3/pi4)*y/r;
        if(m==0)        ylm=sqrt(3/pi4)*z/r;
        break;

    case 2:
        if(m==-2)           ylm=0.5*sqrt(15/pi)*x*y/r2;
        if(m==-1)           ylm=0.5*sqrt(15/pi)*y*z/r2;
        if(m==0)            ylm=0.25*sqrt(5.0/pi)*(2*z*z-x*x-y*y)/r2;
        if(m==1)            ylm=0.5*sqrt(15.0/pi)*x*z/r2;
        if(m==2)            ylm=0.25*sqrt(15.0/pi)*(x*x-y*y)/r2;
        break;



    case 3:
        if(m==-3)           ylm=0.25*sqrt(35.0/2.0/pi)*(3.0*x*x-y*y)*y/r3;
        if(m==-2)           ylm=0.5*sqrt(105.0/pi)*x*y*z/r3;
        if(m==-1)           ylm=0.25*sqrt(21.0/2.0/pi)*y*(4.0*z*z-x*x-y*y)/r3;;
        if(m==0)            ylm=0.25*sqrt(7.0/pi)*(2.0*z*z-3.0*x*x-3.0*y*y)/r3;
        if(m==1)            ylm=0.25*sqrt(21.0/2/pi)*x*(4.0*z*z-x*x-y*y)/r3;
        if(m==2)            ylm=0.25*sqrt(105.0/pi)*(x*x-y*y)*z/r3 ;
        if(m==3)            ylm=0.25*sqrt(35.0/2.0/pi)*(x*x-3.0*y*y)*x/r3 ;
        break;

    default:
        ylm=1.0;
    }
    return ylm;
}



double EHMO::Rnl(int idx,vector3 pos)
{
    SlateBasisSets * bas= getBasisSet(idx);

    double value=0.0;
    int n=bas->n;
    vector3 v=bas->coord-pos;

    double r=v.length();
    if(r<0.0001) r=0.0001;

    //double c=sqrt(Factorial(2*n));
    //double rn1=pow(r,n-1);

    double zeta=bas->Exp[0];
    //uint l=bas->l;
    //int m=bas->m;

    //double x=v.x(),  y=v.y(),     z=v.z();


    //multiple zeta
    value=0.0;
    double R=1.0;
    double coeff;
    for(auto i=0;i<bas->numZeta;i++)
    {
        zeta=bas->Exp[i];
        coeff=bas->Coeff[i];

        switch (n)
        {
        case 1:
            R=2.0*pow(zeta,1.5)*exp(-zeta*r);
            break;

        case 2:
            R=2.0/3.0*pow(zeta,2.5)*r*exp(-zeta*r);
            break;

        case 3:
            R=2.0/15.0*sqrt(10.0)*pow(zeta,3.5)*r*r*exp(-zeta*r);
            break;

        case 4:
            R=2.0/sqrt(105.0)*pow(zeta,4.5)*r*r*r*exp(-zeta*r);
            break;

        case 5:
            R=2.0/45*sqrt(2.0/7.0)*pow(zeta,5.5)*r*r*r*r*exp(-zeta*r);
            break;

        case 6:
            R=2.0/45*sqrt(2.0/231.0)*pow(zeta,5.5)*r*r*r*r*r*exp(-zeta*r);
            break;

        case 7:
            R=4.0/315/sqrt(429.0)*pow(zeta,6.5)*r*r*r*r*r*r*exp(-zeta*r);
            break;

        default:
            R=pow(2.0*zeta,n+1.0/2)/sqrt(Factorial(2*n))*pow(r,n-1)*exp(-zeta*r);
        }

        value+=coeff*R;
    }

    return value;
}



double EHMO::Psi(vector3 pos)
{
    double Psi=0.0;
    const auto& eigvec = huckelEigVecs[idxActiveMO];
    for (unsigned int i=0;i<numBasisSets();i++)
    {
        double coeff = eigvec[i];
        if (fabs(coeff) < 0.001) continue;
        Psi+= coeff * AO(i,pos);
    }
    return Psi;
}


double EHMO::Psi(double x, double y, double z)
{
    vector3 p(x,y,z);
    return Psi(p);
}


