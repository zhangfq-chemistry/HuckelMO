// Associated Legendre polynomial
double EHMO::plm(int l, int a, double theta)
{
    int end =  (l - a - ((1 - pow(-1 ,l - a))/2)) / 2;

    double interim;
    double cosTheta=cos(theta),
           sinTheta=sin(theta);


    double tvalue=0.0;
    double powTerm;
    for (int k=0; k <= end;  k++)
    {
        if  (l - a - 2*k == 0)
            powTerm=1.0;
        else
            powTerm=pow(cosTheta, (l - a - 2 * k));

        tvalue += pow(-1, k) * binom(a + k, k) * binom(2 * l - 2 * k, l - k)
                   * binom(l - k, l - a - 2 * k) * powTerm;
    }


    if(a==0)
        interim = 1.0/pow(2, l);
    else
        interim = pow(-1,a) * pow(sinTheta,a)/pow(2, l);

    interim = interim * sqrt((2 * l + 1) / (2 * binom(l, a) * binom(l + a, a)));
    double value = interim * tvalue;

    return value;
}




double EHMO::Phi(double m1, double phi)
{
    int kd;
    if (m1 == 0)
        kd = 1;
    else
        kd = 0;

    double  value = 1.0/(sqrt(pi * (1.0 + kd)));

    if (m1 >= 0)
        value = value * cos(abs(m1) * phi);
    else
        value = value * sin(abs(m1) * phi);
    return value;
}




//(1) formula 21 of Int. J. Contemp. Math. Sciences, Vol. 5, 2010, no. 27, 1309-1321
//(2) special case of Clebsch-Gordan coefficient
double EHMO::clm(int l1,int l2, int L,int m1, int m2,int M)
{
    // KroneckerDelta
    if (M != m1 + m2)
        return 0.0;

    if (L < M)
        return 0.0;

    //(L >= M)
    double tvalue=0.0;
    double interim;
    int lower = max1(0, (l1 - m1 - (L - M)), (l2 + m2 - (L + M)));
    int upper= min1( (l1 - m1), (l2 + m2), (l1 + l2 - L));

    for (int t=lower; t<upper+1; t++)
        tvalue +=  pow(-1, t)
                   * binom(l1 + l2 - L, t)
                   * binom(L - M, l1 - m1 - t) * binom(L + M, l2 + m2 - t);


    interim = (2 * l1 + 1) * (2 * l2 + 1) * binom(l1 + l2 + L + 1, l1 - l2 + L)
               * binom(l1 + l2 + L + 1, l2 - l1 + L)
               * binom(2 * l1, l1 + m1) * binom(2 * l2, l2 + m2);

    interim = 1.0/interim;
    interim = sqrt(interim * (2 * L + 1) * (2 * L + 1) * binom(l1 + l2 + L + 1, l1 + l2 - L) * binom(2 * L, L + M));

    double value = interim * tvalue * pow(-1.0, (m1 + abs(m1) + m2 + abs(m2) + M + abs(M))/2);

    return value;
}


//Psi=R*slm, where slm is real type of Ylm
double EHMO::slm(int l1,int  m1, double theta, double phi)
{
    double value = 0.0;

    if (abs(m1) > l1)
        value = 0.0;
    else
        value = plm(l1, abs(m1), theta) * Phi(m1, phi);

    return value;
}





//overall formula 20
double EHMO::tlm(int a, int l1, int m1,int l2, int m2, double theta, double phi)
{
    double value = 0.0;

    int y1 = abs(m1);
    int y2 = abs(m2);

    int kd1,kd2,kd3,kd4,kd5;

    //lamda=a
    if (a == 0)  kd1 = 1;
    else         kd1 = 0;


    if (m1 == 0)  kd2 = 1;
    else          kd2 = 0;

    if (m2 == 0)  kd3 = 1;
    else          kd3 = 0;

    //vector initialization
    if(y1 == y2 &&  em(m1, m2)< 0)
        return 0.0;


    double ivalue=0.0;
    for (int i=-1; i<=1; i=i+2)
    {
        double Lvalue=0.0;
        for (int L = abs(l1 - l2); L< l1 + l2 + 1; L=L+2)
        {
            if (i == int( em(m1, m2 )))
                kd4 = 1;
            else
                kd4 = 0;

            if ( int (em(m1, m2) * abs(i * y1 + y2)) == 0)
                kd5 = 1;
            else
                kd5 = 0;

            //source code from https://github.com/matthiaslein
            double in1 = 1.0*pow( em(i * y1 + y2, m1),  kd4);
            //double in1 = 1.0*pow( em(0, m1),  kd4);
            double in2 = 1.0*clm(l1, l2, L, i * y1, y2, i * y1 + y2);
            double in3 = 1.0*clm(l1, l2, L, a, -a, 0);
            double in4 = sqrt( ((2.0 * pi) / (2.0 * L + 1.0)) * (1.0 + kd5) );
            double in5 = 1.0*slm(L, em(m1, m2) * abs(y2 + i * y1), theta, phi);
            Lvalue += in1 * in2 * in3 * in4 * in5;
        }
        ivalue += Lvalue;
    }

    double prefactor=2.0 * pow (-1.0, y1 + y2) / (1.0 + kd1) / sqrt((1.0 + kd2) * (1.0 + kd3));
    value = ivalue * prefactor;

    return value;
}





double EHMO::overlap(int n1, int l1, int n2, int l2, int lambda_, double p, double t)
{
    double  p1 = 1.0 + t;
    double  p2 = 1.0 - t;
    double  pt = p * t;

    int  a1=0, b1=0;

    if ((l1 - lambda_) % 2 == 0)
        a1 = -lambda_;
    else
        a1 = -lambda_ + 1;

    if ((l2 + lambda_) % 2 == 0)
        b1 = lambda_;
    else
        b1 = lambda_ + 1;

    double numerator = pow(p1, n1 + 0.5) * pow(p2 ,n2 + 0.5);
    double denominator = sqrt(1.0* Factorial(2 * n1)) * sqrt(Factorial(2 * n2));
    double prefactor = numerator / denominator;

    double ivalue,jvalue,kvalue,mvalue;
    int i,j,k,m;

    ivalue=0.0;
    for (i = a1; i<l1 + 1; i=i+2)
    {
        jvalue=0.0;
        for (j = b1; j<l2 + 1; j=j+2)
        {
            kvalue=0.0;
            for (k = 0; k<i + j + 1; k++ )
            {
                mvalue=0.0;
                for (m = 0; m<n1 + n2 - i - j + 1; m++)
                    mvalue += (Fmn(m, n1 - i, n2 - j) * Bn3(m + k, pt) * An3(n1 + n2 + 1, n1 + n2 - i - j - m + k, p));

                kvalue += (mvalue * Fmn(k, i + lambda_, j - lambda_));
            }
            jvalue+=(kvalue * galbet(l1, l2, lambda_, i, j));
        }
        ivalue+=jvalue;
    }

    double value = ivalue * prefactor * pow(-1 ,l2 + lambda_);
    return value;
}



